export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Column bitmasks, bit n set means row n is lit. */
const GLYPHS = new Map<string, number[]>();

for (const [char, art] of Object.entries(ART)) {
  const rows = art.split(' ');
  const columns: number[] = [0, 0, 0, 0, 0];
  for (let y = 0; y < GLYPH_H; y++) {
    const row = rows[y] ?? '.....';
    for (let x = 0; x < GLYPH_W; x++) {
      if (row[x] === '#') columns[x]! |= 1 << y;
    }
  }
  GLYPHS.set(char, columns);
}

const FALLBACK = GLYPHS.get('?')!;

export function glyphFor(char: string): number[] {
  return GLYPHS.get(char) ?? FALLBACK;
}

export function textWidth(text: string, scale: number, tracking = 1): number {
  if (text.length === 0) return 0;
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}
